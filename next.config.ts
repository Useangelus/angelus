import type { NextConfig } from "next";

// Time-based revalidation (fetch `next.revalidate` + route `revalidate`) is all this site needs,
// so Cache Components stay off.

// Sent with every response. No full Content-Security-Policy on purpose: the 3D scene, WalletConnect
// relays and the logo CDN would need a long allow-list that breaks quietly; framing is still forbidden.
const SECURITY_HEADERS = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'; base-uri 'self'; object-src 'none'" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: SECURITY_HEADERS }];
  },
};

export default nextConfig;
